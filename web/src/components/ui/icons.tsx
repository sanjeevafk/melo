// Zero-dependency inline SVG icons
import { forwardRef } from "react";
import type { ComponentPropsWithoutRef } from "react";

export interface IconProps extends ComponentPropsWithoutRef<"svg"> {
  size?: number | string;
  strokeWidth?: number | string;
}

type IconNode = [tag: string, attrs: Record<string, string | number>];

function createIcon(name: string, nodes: IconNode[]) {
  const IconComponent = forwardRef<SVGSVGElement, IconProps>(
    (
      {
        size = 24,
        strokeWidth = 2,
        color = "currentColor",
        fill = "none",
        className,
        children,
        ...props
      },
      ref,
    ) => (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill={fill}
        stroke={color}
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        {...props}
      >
        {nodes.map(([tag, attrs], idx) => {
          const Tag = tag as keyof React.JSX.IntrinsicElements;
          const { key: nodeKey, ...restAttrs } = attrs;
          return <Tag key={nodeKey ?? idx} {...restAttrs} />;
        })}
        {children}
      </svg>
    ),
  );
  IconComponent.displayName = name;
  return IconComponent;
}

